/**
 * SQLite LIKE 的转义。
 *
 * `%` 匹配任意串、`_` 匹配任意单字符——这两个字符在我们的数据里都是会真实出现的：
 * 用户 id 长成 `u_1`，消息正文里也常有 `100%`。不转义就拼进 LIKE 的话，搜 `a_b`
 * 会连 `aXb` 一起命中，判断 `"u_1"` 在不在 mentions 里会把 `"uX1"` 也算进来。
 *
 * 反斜杠自己必须一起转义，否则用户输入的 `\%` 里那个 `%` 又变回通配符。
 * 用这个函数拼出来的模式，SQL 那边必须配 `ESCAPE '\'`，两者是一对，不能只写一半。
 */
export const escapeLike = (value) => String(value).replace(/[\\%_]/g, (ch) => `\\${ch}`);
